    private void verificarConexion() {
        try (Connection conn = new CreateConection().getConection()) {
            if (conn != null) {
                lblEstadoBD.setText("Base de datos: conectada");
            } else {
                lblEstadoBD.setText("Base de datos: sin conexión");
            }
        } catch (SQLException e) {
            lblEstadoBD.setText("Base de datos: sin conexión");
        }
    }
