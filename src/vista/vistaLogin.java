    private boolean validarCampos() {
        if (txtUsuario.getText().trim().isEmpty()) {
            Mensajes.aviso(this, "Ingrese su usuario.");
            txtUsuario.requestFocus(); return false;
        }
        if (pwdContrasena.getPassword().length == 0) {
            Mensajes.aviso(this, "Ingrese su contraseña.");
            pwdContrasena.requestFocus(); return false;
        }
        return true;
    }
    
    private boolean baseDeDatosDisponible() {
        try (Connection conexion = new CreateConection().getConection()) {
            return conexion != null && conexion.isValid(2);
        } catch (SQLException e) {
            return false;
        }
    }
    
    private void iniciarSesion() {
        if (!validarCampos()) return;

        String nombre = txtUsuario.getText().trim();
        char[] clave = pwdContrasena.getPassword();
        String hash = Seguridad.sha256(new String(clave));
        Arrays.fill(clave, ' ');

        usuario autenticado = controlador.validarLogin(nombre, hash);

        if (autenticado != null) {
            new vistaVentanaprincipal(autenticado.getUsuario()).setVisible(true);
            dispose();
            return;
        }

        if (!baseDeDatosDisponible()) {
            Mensajes.error(this, """
                                 No se pudo conectar a la base de datos.
                                 Verifique que PostgreSQL est\u00e9 en ejecuci\u00f3n y que db_config.properties sea correcto.""");
            return;
        }

        Mensajes.error(this, "Usuario o contraseña incorrectos, o el usuario está inactivo.");
        pwdContrasena.setText("");
        pwdContrasena.requestFocus();
    }
    
    
