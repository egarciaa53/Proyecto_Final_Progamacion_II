    private void cargarTabla(String filtro) {
        listaDepartamentos = controlador.obtenerDepartamentos();
        DefaultTableModel modelo = (DefaultTableModel) tblDepartamentos.getModel();
        modelo.setRowCount(0);
        String f = filtro.trim().toLowerCase();
        for (departamento d : listaDepartamentos) {
            if (f.isEmpty() || d.getDescripcion().toLowerCase().contains(f)) {
                modelo.addRow(new Object[]{d.getId_departamento(), d.getDescripcion()});
            }
        }
    }
    private int siguienteId() {
        int max = 0;
        for (departamento d : listaDepartamentos) max = Math.max(max, d.getId_departamento());
        return max + 1;
    }

    private void limpiarFormulario() {
        tblDepartamentos.clearSelection();
        txtIdDepartamento.setText(String.valueOf(siguienteId()));
        txtDescripcion.setText("");
        txtDescripcion.requestFocus();
    }
    private boolean validarCampos() {
        String desc = txtDescripcion.getText().trim();
        if (desc.isEmpty()) { Mensajes.aviso(this, "La descripción es obligatoria."); txtDescripcion.requestFocus(); return false; }
        if (desc.length() > MAX_DESCRIPCION) { Mensajes.aviso(this, "Máximo " + MAX_DESCRIPCION + " caracteres."); return false; }
        return true;
    }
    private departamento leerFormulario() {
        return new departamento(Integer.parseInt(txtIdDepartamento.getText()), txtDescripcion.getText().trim());
    }
    private void mostrarEnFormulario() {
        int fila = tblDepartamentos.getSelectedRow();
        if (fila < 0) return;
        txtIdDepartamento.setText(tblDepartamentos.getValueAt(fila, 0).toString());
        txtDescripcion.setText(tblDepartamentos.getValueAt(fila, 1).toString());
    }
