    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (tblDepartamentos.getSelectedRow() < 0) { Mensajes.aviso(this, "Seleccione un departamento."); return; }
        if (!Mensajes.confirmar(this, "¿Eliminar el departamento seleccionado?")) return;
        if (controlador.eliminarDepartamento(Integer.parseInt(txtIdDepartamento.getText()))) {
            cargarTabla(""); limpiarFormulario();
        } else Mensajes.error(this, "No se pudo eliminar. Es probable que tenga empleados asociados.");
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
        if (tblDepartamentos.getSelectedRow() < 0) { Mensajes.aviso(this, "Seleccione un departamento."); return; }
        if (!validarCampos()) return;
        if (controlador.actualizarDepartamento(leerFormulario())) {
            cargarTabla(""); limpiarFormulario(); Mensajes.info(this, "Departamento actualizado.");
        } else Mensajes.error(this, "No se pudo actualizar.");
    }//GEN-LAST:event_btnModificarActionPerformed

